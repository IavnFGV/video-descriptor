"""Bundle the shared design-system CSS for the existing /native.css route."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['design-system/tokens.css', 'design-system/components.css', 'windows-app/ui/layout.css']
TARGET = ROOT / 'windows-app/ui/app.css'


def bundle():
    chunks = ['/* Generated by scripts/build-ui-css.py. Edit the sources, not this file. */']
    for name in SOURCES:
        chunks.append(f'/* Source: {name} */\n' + (ROOT / name).read_text(encoding='utf-8').strip())
    return '\n\n'.join(chunks) + '\n'


if __name__ == '__main__':
    expected = bundle()
    if '--check' in sys.argv:
        if TARGET.read_text(encoding='utf-8') != expected:
            raise SystemExit('CSS bundle is stale: run python scripts/build-ui-css.py')
        print('PASS: native.css matches shared tokens/components/layout.')
    else:
        TARGET.write_text(expected, encoding='utf-8')
