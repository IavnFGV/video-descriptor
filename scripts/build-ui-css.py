"""Bundle the shared design-system CSS for the existing /native.css route."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['design-system/tokens.css', 'design-system/components.css', 'windows-app/ui/layout.css']
TARGET = ROOT / 'windows-app/ui/app.css'
SHARED = ['design-system/tokens.css', 'design-system/components.css', 'design-system/surfaces.css']
BUNDLES = {
    'windows-app/ui/app.css': SOURCES,
    'video_descriptor/assets/create.css': SHARED + ['design-system/workspace.css'],
    'video_descriptor/assets/editor.css': SHARED + ['design-system/editor.css'],
}


def bundle(sources=SOURCES):
    chunks = ['/* Generated by scripts/build-ui-css.py. Edit the sources, not this file. */']
    for name in sources:
        chunks.append(f'/* Source: {name} */\n' + (ROOT / name).read_text(encoding='utf-8').strip())
    return '\n\n'.join(chunks) + '\n'


if __name__ == '__main__':
    for target, sources in BUNDLES.items():
        expected = bundle(sources)
        path = ROOT / target
        if '--check' in sys.argv:
            if path.read_text(encoding='utf-8') != expected:
                raise SystemExit('CSS bundle is stale: ' + target)
        else:
            path.write_text(expected, encoding='utf-8')
    print('PASS: all production CSS bundles match shared sources.')
