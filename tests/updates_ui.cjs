const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const nodes = new Map();
const node = id => {
  if(!nodes.has(id))nodes.set(id,{hidden:true,textContent:'',open:false,setAttribute(){},showModal(){this.open=true;},close(){this.open=false;}});
  return nodes.get(id);
};
let result={installed:{version:'0.9.3',build:7},latest:null,update_available:false,status:'ok'};
const calls=[];
const context={document:{getElementById:node},window:{},fetch:async(url,options)=>{calls.push([url,options]);return {ok:true,json:async()=>result};}};
vm.runInNewContext(fs.readFileSync('windows-app/ui/updates.js','utf8'),context);
const tick=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
  context.window.updatesUI.init('instance');await tick();
  assert.equal(node('updates-badge').hidden,true);
  assert.match(node('updates-status').textContent,/актуальную/);
  result={...result,update_available:true,latest:{version:'0.9.3',build:8,title:'Title',notes:'<img src=x onerror=alert(1)>',url:'https://evil.invalid'}};
  await context.window.updatesUI.refresh();
  assert.equal(node('updates-badge').hidden,false);
  assert.equal(node('updates-installed').textContent,'Установлено: 0.9.3 (build 7)');
  assert.equal(node('updates-available').textContent,'Доступно: 0.9.3 (build 8)');
  assert.equal(node('updates-notes').textContent,result.latest.notes);
  assert.equal(node('updates-notes').innerHTML,undefined);
  node('updates-badge').onclick();assert.equal(node('updates-dialog').open,true);
  node('updates-later').onclick();assert.equal(node('updates-dialog').open,false);
  await node('updates-open').onclick();
  assert.equal(calls.at(-1)[0],'/api/setup/external');
  assert.equal(calls.at(-1)[1].body,'{"page":"update-release"}');
  node('updates-check').onclick();await tick();
  assert.equal(calls.at(-1)[0],'/api/updates/check');
  assert.equal(calls.at(-1)[1].method,'POST');
  result={...result,status:'unsupported'};
  await context.window.updatesUI.refresh();
  assert.equal(node('updates-badge').hidden,true);
  assert.match(node('updates-status').textContent,/сборки разработки/);
  context.fetch=async()=>{throw Error('offline');};
  await context.window.updatesUI.refresh();
  assert.match(node('updates-status').textContent,/недоступен/);
  assert.equal(node('updates-check').disabled,false);
  console.log('Update UI tests passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
